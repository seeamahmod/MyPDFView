// Inlines the pdf.js library + worker into a TS module so the PDF engine
// (which runs inside a WebView) works fully offline. Runs on postinstall.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const build = join(root, 'node_modules', 'pdfjs-dist', 'legacy', 'build');
const lib = readFileSync(join(build, 'pdf.min.mjs'), 'utf8');
const worker = readFileSync(join(build, 'pdf.worker.min.mjs'), 'utf8');

const out = join(root, 'src', 'pdf', 'generated', 'pdfjsSource.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/build-pdfjs.mjs — do not edit.\n' +
    `export const PDFJS_LIB = ${JSON.stringify(lib)};\n` +
    `export const PDFJS_WORKER = ${JSON.stringify(worker)};\n`,
);
console.log(`pdf.js inlined → ${out} (${Math.round((lib.length + worker.length) / 1024)} KB)`);
